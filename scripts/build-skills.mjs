import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const root=resolve(import.meta.dirname,'..');
const catalog=JSON.parse(await readFile(resolve(root,'skills/catalog.json'),'utf8'));
const ids=new Set();
const full=[];
for(const skill of catalog){
  if(!/^[a-z][a-z0-9-]{0,63}$/.test(skill.id)||ids.has(skill.id))throw Error('Invalid or duplicate skill');
  ids.add(skill.id);
  const text=await readFile(resolve(root,'skills',skill.id,'SKILL.md'),'utf8');
  if(!text.startsWith('---\n')||!text.includes('description:'))throw Error('Invalid SKILL.md: '+skill.id);
  const instructions=text.replace(/^---\n[\s\S]*?\n---\n/,'').trim();
  full.push({...skill,instructions});
}
const publicCatalog=full.map(({instructions,...skill})=>skill);
await writeFile(resolve(root,'worker/skills-catalog.js'),'// Generated by scripts/build-skills.mjs.\nexport default '+JSON.stringify(full,null,2)+';\n');
await writeFile(resolve(root,'arena-skills-catalog.js'),'// Generated metadata; instructions are loaded by the server only.\nwindow.ArenaSkillCatalog='+JSON.stringify(publicCatalog)+';\n');
console.log('Built '+full.length+' skills; public catalog contains metadata only.');
